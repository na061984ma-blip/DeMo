export function computeProjectStats(project: VentureProject): ComputedProjectStats {
  const allFlats = project.floors.flatMap((f) => f.flats);
  return {
    totalFloors: project.floors.length,
    totalFlats: allFlats.length,
    availableFlats: allFlats.filter((f) => f.status === 'Available').length,
    soldFlats: allFlats.filter((f) => f.status === 'Sold').length,
    rentedFlats: allFlats.filter((f) => f.status === 'Rented').length,
    reservedFlats: allFlats.filter((f) => f.status === 'Reserved').length,
  };
}

/**
 * Generates an architecturally consistent, flat-specific room walkthrough graph
 * based on the selected flat's exact bedroom configuration (2 BHK vs 3 BHK vs 4 BHK).
 * Ensures 2 BHK flats never show unrelated 3rd/4th bedrooms.
 */
