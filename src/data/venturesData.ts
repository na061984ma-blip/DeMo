function buildFloors(
  projectId: string,
  floorDefs: {
    floorNumber: number;
    floorLabel: string;
    note: string;
    units: {
      suffix: string;
      bhk: string;
      carpet: number;
      builtUp: number;
      superBuiltUp: number;
      landShare: number;
      facing: DirectionKey;
      balconies: string;
      beds: number;
      baths: number;
      parking: string;
      price: number;
      status: FlatStatus;
      panoId: string;
    }[];
  }[]
): FloorData[] {
  return floorDefs.map((f, idx) => {
    const flats: FlatUnit[] = f.units.map((u) => {
      const flatNumber =
        f.floorNumber === 0 ? `G-${u.suffix}` : `${f.floorNumber}${u.suffix}`;
      return {
        id: `${projectId}-f${f.floorNumber}-${u.suffix}`,
        flatNumber,
        floorNumber: f.floorNumber,
        floorLabel: f.floorLabel,
        bhkConfig: u.bhk,
        carpetAreaSqFt: u.carpet,
        builtUpAreaSqFt: u.builtUp,
        superBuiltUpAreaSqFt: u.superBuiltUp,
        landShareSqYds: u.landShare,
        facing: u.facing,
        balconies: u.balconies,
        bedrooms: u.beds,
        bathrooms: u.baths,
        parking: u.parking,
        priceNumeric: u.price,
        priceLabel: `$${u.price.toLocaleString('en-US')}`,
        status: u.status,
        panoramaViewpointId: u.panoId,
      };
    });

    return {
      floorNumber: f.floorNumber,
      floorLabel: f.floorLabel,
      floorPlanImage: FLOOR_PLAN_IMAGES[idx % FLOOR_PLAN_IMAGES.length],
      floorPlanNote: f.note,
      flats,
    };
  });
}

